"""Tables and text numbers for the equal-particle planner comparison. 2026-10-07.

Writes, into OUT_DIR (default: this directory):
  table1_iclr.tex          main Table 1 (tab:planners): GD, GRASP, CEM, MPPI and ours,
                           every planner with 12 particles and 150 iterations;
                           success rate with mean iterations to success
  table_abl_gd_grasp.tex   appendix (tab:abl-1particle): GD and GRASP with a
                           single particle for 150 iterations
  table_abl_cem.tex        appendix (tab:abl-cem): CEM with 30 samples for 5
                           iterations
  table_ci.tex             appendix (tab:ci): 95% Wilson intervals for every
                           success rate of the three tables (and Cube), and the
                           exact McNemar p-value of ours against the strongest
                           baseline of Table 1 in each cell, on paired seeds
  equal_particle_numbers.json   every number quoted in the text

Success and iterations come from writeup/equal_particle_stats.py. Time to
success is reported in iterations, not wall clock: with every planner holding
12 particles an iteration is the common unit, whereas wall clock depends on how
each implementation parallelises (GRASP optimises the intermediate states of a
trajectory in parallel; GD, CEM and ours roll the world model out sequentially).
"""
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from equal_particle_stats import (ROOT, ENVS, HS, outcomes,  # noqa: E402
                                  cube_nontrivial, wilson, paired)

OUT_DIR = os.environ.get("OUT_DIR", os.path.dirname(os.path.abspath(__file__)))
MAIN = [("GD", "gds12"), ("GRASP", "grasp12"), ("CEM", "cem12"), ("MPPI", "mppi12"),
        ("Ours", "ours")]
BASELINES = ["gds12", "grasp12", "cem12", "mppi12"]   # equal-particle baselines
CELLS = [(e, H) for _, e in ENVS for H in HS]


def summary(arm, env, H=5):
    o = outcomes(arm, env, H)
    n = len(o)
    ok = [s for s, (v, _) in o.items() if v]
    its = [o[s][1] for s in ok]
    return dict(n=n, succ=100.0 * len(ok) / n if n else None,
                iters=float(np.mean(its)) if its else None, seeds_ok=sorted(ok),
                iters_by_seed={s: o[s][1] for s in ok})


def header(ncol_groups):
    hdr = " & ".join(r"\multicolumn{%d}{c}{%s}" % (len(HS), n) for n, _ in ENVS)
    cmid = " ".join(r"\cmidrule(lr){%d-%d}" % (2 + len(HS) * i, 1 + len(HS) * (i + 1))
                    for i in range(ncol_groups))
    sub = " & ".join(str(H) for _ in ENVS for H in HS)
    return hdr, cmid, sub


def success_rows(rows, stats):
    best = {c: max(stats[a][c]["succ"] for _, a in rows) for c in CELLS}
    lines = []
    for label, a in rows:
        cells = []
        for c in CELLS:
            st = stats[a][c]
            num = (r"\best{%.0f}" % st["succ"]) if st["succ"] == best[c] else "%.0f" % st["succ"]
            cells.append(num if st["iters"] is None else num + r" \tiny{(%.0f)}" % st["iters"])
        name = r"\textbf{%s}" % label if a == "ours" else label
        lines.append((a, f"    {name} & " + " & ".join(cells) + r" \\"))
    return lines


def main():
    arms = ["ours"] + BASELINES + ["gd", "grasp", "cem"]
    stats = {a: {c: summary(a, *c) for c in CELLS} for a in arms}
    cube = {a: summary(a, "cube") for a in arms}
    nt = cube_nontrivial()
    nums = {"cells": {}, "cube": {}, "avg": {}, "paired": {}}
    for a in arms:
        for (e, H) in CELLS:
            st = stats[a][(e, H)]
            assert st["n"] == 100, (a, e, H, st["n"])
            nums["cells"][f"{a}/{e}/H{H}"] = dict(succ=st["succ"], iters=st["iters"])
        c = cube[a]
        assert c["n"] == 50, (a, c["n"])
        okn = sum(1 for s in c["seeds_ok"] if s in nt)
        nums["cube"][a] = dict(all=c["succ"], nontrivial=100.0 * okn / len(nt),
                               iters=c["iters"], n_nontrivial=len(nt))
        nums["avg"][a] = float(np.mean([stats[a][c]["succ"] for c in CELLS]))
    for a in BASELINES + ["gd", "grasp", "cem"]:
        nums["avg"][f"gain_vs_{a}"] = nums["avg"]["ours"] - nums["avg"][a]
    # paired seeds, ours vs each equal-particle baseline
    for a in BASELINES:
        tot_w = tot_l = 0
        for (e, H) in CELLS:
            o, x = outcomes("ours", e, H), outcomes(a, e, H)
            common = sorted(set(o) & set(x))
            assert len(common) == 100, (a, e, H, len(common))
            w = sum(o[s][0] and not x[s][0] for s in common)
            l = sum(x[s][0] and not o[s][0] for s in common)
            nums["paired"][f"{a}/{e}/H{H}"] = (w, l)
            tot_w += w
            tot_l += l
        nums["paired"][f"{a}/total"] = (tot_w, tot_l)
    hdr, cmid, sub = header(len(ENVS))
    ncol = len(CELLS)

    # ---------------- main Table 1
    L = [r"% Generated by writeup/make_equal_particle_tables.py -- do not hand-edit; rerun instead.",
         r"% Requires: \usepackage{booktabs}, \usepackage{xcolor}.",
         r"\definecolor{bestpurple}{HTML}{5B2C87}",
         r"\begin{table}[t]",
         r"  \caption{Planning success rate (\%) at horizons $H\in\{5,10,15\}$, with the mean number of iterations to success in parentheses, over $100$ seeds per setting; Cube is reported in \Cref{sec:exp:planning}. Every planner holds $12$ particles, and a trial succeeds if the plan of one of its first $150$ iterations succeeds in the simulator (\Cref{sec:experiments}). Ours is our planner with the PDE cost. Iteration counts average over successful seeds only. Best success rate per column in bold; $95\%$ intervals and paired tests are in \Cref{tab:ci}.}",
         r"  \label{tab:planners}",
         r"  \centering",
         r"  \setlength{\tabcolsep}{7pt}",
         r"  \renewcommand{\arraystretch}{1.15}",
         r"  \resizebox{1\textwidth}{!}{%",
         r"  \begin{tabular}{l" + "c" * ncol + "}",
         r"    \toprule",
         r"    & " + hdr + r" \\",
         r"    " + cmid,
         r"    Planner & " + sub + r" \\",
         r"    \midrule"]
    for a, line in success_rows(MAIN, stats):
        if a == "ours":
            L.append(r"    \midrule")
        L.append(line)
    L += [r"    \bottomrule", r"  \end{tabular}}", r"\end{table}"]
    open(os.path.join(OUT_DIR, "table1_iclr.tex"), "w").write("\n".join(L) + "\n")

    # ---------------- appendix: 1-particle GD and GRASP
    def abl_table(rows, label, caption):
        T = [r"% Generated by writeup/make_equal_particle_tables.py -- do not hand-edit; rerun instead.",
             r"\begin{table}[!htbp]",
             r"  \caption{" + caption + "}",
             r"  \label{" + label + "}",
             r"  \centering",
             r"  \setlength{\tabcolsep}{7pt}",
             r"  \renewcommand{\arraystretch}{1.15}",
             r"  \resizebox{1\textwidth}{!}{%",
             r"  \begin{tabular}{l" + "c" * ncol + "}",
             r"    \toprule",
             r"    & " + hdr + r" \\",
             r"    " + cmid,
             r"    Planner & " + sub + r" \\",
             r"    \midrule"]
        for a, line in success_rows(rows, stats):
            if a == "ours":
                T.append(r"    \midrule")
            T.append(line)
        T += [r"    \bottomrule", r"  \end{tabular}}", r"\end{table}"]
        return "\n".join(T) + "\n"

    open(os.path.join(OUT_DIR, "table_abl_gd_grasp.tex"), "w").write(abl_table(
        [("GD", "gd"), ("GRASP", "grasp"), ("Ours", "ours")], "tab:abl-1particle",
        r"\textbf{1-particle 150-step ablation.} Planning success rate (\%) with the mean number of iterations to success in parentheses, over $100$ seeds per cell, for GD and GRASP each optimizing a single particle for $150$ iterations. The row of our planner, with $12$ particles, repeats \Cref{tab:planners}. Iteration counts average over successful seeds only. Best success rate per column in bold."))
    open(os.path.join(OUT_DIR, "table_abl_cem.tex"), "w").write(abl_table(
        [("CEM", "cem"), ("Ours", "ours")], "tab:abl-cem",
        r"\textbf{CEM 30-sample 5-step ablation.} Planning success rate (\%) with the mean number of iterations to success in parentheses, over $100$ seeds per cell, for CEM with $30$ samples and $3$ elites per iteration for $5$ iterations, $150$ world-model rollouts in total. The row of our planner, with $12$ particles and $150$ iterations, repeats \Cref{tab:planners}. Iteration counts average over successful seeds only. Best success rate per column in bold."))

    # ---------------- appendix: 95% intervals and paired tests
    def ival(st):
        k = round(st["succ"] * st["n"] / 100)
        lo, hi = wilson(k, st["n"])
        return lo, hi

    def fmt_iv(st):
        lo, hi = ival(st)
        return "%.0f--%.0f" % (lo, hi)

    def fmt_p(p):
        if p < 0.001:
            return "$<$0.001"
        return ("%.3f" % p) if p < 0.1 else ("%.2f" % p)

    COLS = CELLS + [("cube", 5)]
    nums["ci"], nums["p_vs_best"] = {}, {}
    for a in arms:
        for (e, H) in COLS:
            st = cube[a] if e == "cube" else stats[a][(e, H)]
            nums["ci"][f"{a}/{e}/H{H}"] = ival(st)
    best_of = {}
    for (e, H) in COLS:
        get = (lambda a: cube[a]) if e == "cube" else (lambda a, c=(e, H): stats[a][c])
        b = max(BASELINES, key=lambda a: get(a)["succ"])
        oo, ob = outcomes("ours", e, H), outcomes(b, e, H)
        w, l, pv = paired(oo, ob)
        best_of[(e, H)] = b
        nums["p_vs_best"][f"{e}/H{H}"] = dict(baseline=b, ours_only=w, base_only=l, p=pv)
    hdr13 = hdr + r" & Cube"
    cmid13 = cmid + r" \cmidrule(lr){%d-%d}" % (ncol + 2, ncol + 2)
    sub13 = sub + " & 5"
    T = [r"% Generated by writeup/make_equal_particle_tables.py -- do not hand-edit; rerun instead.",
         r"\begin{table}[!htbp]",
         r"  \caption{$95\%$ Wilson intervals (\%) for the success rates of \Cref{tab:planners} (top) and of \Cref{tab:abl-1particle,tab:abl-cem} (bottom), over $100$ seeds per cell and $50$ on Cube, and the exact McNemar $p$-value of our planner against the strongest baseline of \Cref{tab:planners} in each cell, on the paired seeds (\Cref{app:ci}).}",
         r"  \label{tab:ci}",
         r"  \centering",
         r"  \setlength{\tabcolsep}{5pt}",
         r"  \renewcommand{\arraystretch}{1.15}",
         r"  \resizebox{1\textwidth}{!}{%",
         r"  \begin{tabular}{l" + "c" * (ncol + 1) + "}",
         r"    \toprule",
         r"    & " + hdr13 + r" \\",
         r"    " + cmid13,
         r"    Planner & " + sub13 + r" \\",
         r"    \midrule"]
    for label, a in MAIN:
        if a == "ours":
            T.append(r"    \midrule")
        name = r"\textbf{%s}" % label if a == "ours" else label
        T.append(f"    {name} & " + " & ".join(
            fmt_iv(cube[a] if e == "cube" else stats[a][(e, H)]) for (e, H) in COLS) + r" \\")
    T.append(r"    $p$, ours vs.\ strongest & " + " & ".join(
        fmt_p(nums["p_vs_best"][f"{e}/H{H}"]["p"]) for (e, H) in COLS) + r" \\")
    T.append(r"    \midrule")
    for label, a in [("GD (1 particle)", "gd"), ("GRASP (1 particle)", "grasp"),
                     (r"CEM ($30\times5$)", "cem")]:
        T.append(f"    {label} & " + " & ".join(
            r"\textendash" if e == "cube" else fmt_iv(stats[a][(e, H)]) for (e, H) in COLS) + r" \\")
    T += [r"    \bottomrule", r"  \end{tabular}}", r"\end{table}"]
    open(os.path.join(OUT_DIR, "table_ci.tex"), "w").write("\n".join(T) + "\n")

    json.dump(nums, open(os.path.join(OUT_DIR, "equal_particle_numbers.json"), "w"),
              indent=1, default=lambda x: None if x is None else x)
    # console summary
    for a in arms:
        print(f"{a:8s} avg {nums['avg'][a]:5.1f}  cube {nums['cube'][a]['all']:.0f}/"
              f"{nums['cube'][a]['nontrivial']:.0f} it {nums['cube'][a]['iters']:.1f}")
    for k, v in nums["avg"].items():
        if k.startswith("gain"):
            print(k, round(v, 1))
    print("paired totals", {k: v for k, v in nums["paired"].items() if k.endswith("total")})


if __name__ == "__main__":
    main()
