"""Emit the cube results table.

Cube is NOT part of the shared H in {5,10,15} grid and must not be dropped into
it: it runs LeFlow's protocol (github.com/hsiangwei0903/LeFlow, config/eval/
cube.yaml) -- goal_H=5 (= 5 blocks x action_block 5 = 25 env steps, matching
eval.goal_offset_steps=25), goal_source=dset, 50 seeds, with the reference
success test ||block - target|| <= 0.04 m. H=15 is not even expressible there:
75 env steps against a 50-step episode cap.

Both columns are reported on purpose. 42% of the sampled windows are TRIVIAL --
the block already sits within the 0.04 m radius, so the goal holds at t=0 and
any planner scores them. That is a property of the reference benchmark (LeFlow
samples start rows uniformly with no movement filter), not of our sampling, so
the all-seeds column is inflated by roughly that much and the non-trivial column
is the one that discriminates.
"""
import glob
import os

import numpy as np

ROOT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "sweep_cube_leflow")
ARMS = [("gd", "GD (tuned, ours)"), ("grasp", "GRASP"),
        ("mpc_cem", "CEM (LeFlow's solver)"), ("fk", "FK (ours)")]


def load(arm):
    out = {}
    for f in glob.glob(f"{ROOT}/{arm}/seed_*/result.txt"):
        s = int(os.path.basename(os.path.dirname(f)).replace("seed_", ""))
        out[s] = int(open(f).read().split()[0])
    return out


def displacements():
    d = {}
    for p in glob.glob(f"{ROOT}/fk/seed_*/traj.npz"):
        s = int(os.path.basename(os.path.dirname(p)).replace("seed_", ""))
        z = np.load(p, allow_pickle=True)
        a = np.asarray(z["state_0"]).ravel()
        g = np.asarray(z["state_g"]).ravel()
        if a.size >= 17:
            d[s] = float(np.linalg.norm(g[14:17] - a[14:17]))
    return d


def main():
    disp = displacements()
    nt = sorted(s for s, v in disp.items() if v > 0.04)
    rows, res = [], {}
    for a, _ in ARMS:
        res[a] = load(a)
    for a, label in ARMS:
        ok = res[a]
        tot, n = sum(ok.values()), len(ok)
        ntok = sum(ok.get(s, 0) for s in nt)
        bold = r"\textbf{%s}" if a == "fk" else "%s"
        rows.append(f"    {label:<24} & {n:>3} & " +
                    (bold % f"{100*tot/max(n,1):.0f}") + " & " +
                    (bold % f"{100*ntok/max(len(nt),1):.0f}") + r" \\")
    tex = "\n".join([
        r"% Generated by writeup/make_cube_table.py -- do not hand-edit.",
        r"% Cube uses LeFlow's protocol, NOT the shared H grid. See the caption.",
        r"\begin{table}[t]",
        r"  \centering",
        r"  \caption{OGBench cube, under the LeFlow evaluation protocol: goal drawn",
        r"  $25$ environment steps ahead in an expert episode ($\mathrm{goal}_H=5$",
        r"  planning blocks $\times$ frameskip $5$), $50$ seeds, success when the",
        r"  block is within $0.04$\,m of its target. \textbf{Trivial goals are",
        r"  reported separately}: in $42\%$ of sampled windows the block already",
        r"  lies inside the success radius, so the goal holds before any planning",
        r"  and every planner scores them. This follows from the reference",
        r"  protocol, which samples start indices uniformly with no filter on",
        r"  block motion; the non-trivial column is therefore the discriminating",
        r"  one. GD is our tuned configuration --- the generic one diverges on",
        r"  this environment --- so the comparison is against a strengthened",
        r"  baseline, and CEM is LeFlow's own solver at its own settings.}",
        r"  \label{tab:cube}",
        r"  \begin{tabular}{lccc}",
        r"    \toprule",
        r"    Planner & $n$ & All seeds (\%) & Non-trivial (\%) \\",
        r"    \midrule",
    ] + rows + [
        r"    \bottomrule",
        r"  \end{tabular}",
        r"\end{table}",
    ]) + "\n"
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "cube_table.tex")
    open(out, "w").write(tex)
    print(f"trivial {len(disp)-len(nt)}/{len(disp)} ({100*(len(disp)-len(nt))/max(len(disp),1):.0f}%), non-trivial n={len(nt)}\n")
    print(tex)


if __name__ == "__main__":
    main()
