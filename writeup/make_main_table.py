"""Generate the main results table: planners as rows, environment x horizon as columns.

Each cell is the success rate with the mean number of optimiser iterations to
success in parentheses, averaged over the SUCCESSFUL seeds only -- failures sit
at the 150-iteration cap and would otherwise pull the mean toward the budget
rather than toward the convergence speed.

The iteration count is the index of the first passing evaluation in run.log.
That source is used for every planner rather than seed_success_log.txt, because
planning/grasp.py is the one planner that does not write the latter. The two
agree exactly where both exist: checked on all 199 successful point-maze H=10
seeds of GD, CEM and ours, with zero disagreements.

An iteration is NOT a common unit across planners: CEM evaluates 300 samples per
iteration, GD one, ours num_particles. The parenthesised numbers are therefore
comparable down a column only within a planner, not across planners; they are
reported as a convergence-speed statistic, not as a compute comparison.

Cube is reported separately in writeup/cube_table.tex.

Colours are the figure palette from figs/iclr_style.py so the table reads as part
of the same system as the plots: PINK #F27DB4 marks our method, NAVY #1C2464 is
the ink for headers and winning entries, and a light pink wash tints the best
entry in each column.

Requires \\usepackage[table]{xcolor} and booktabs in the preamble.
"""
import glob, math, os

ARMS = ["GD", "GRASP", "CEM", "Ours"]
LABEL = {"GD": "GD", "GRASP": "GRASP", "CEM": "CEM", "Ours": "Ours"}
PAT = {"GD": "sweep/%s/gd_H%d", "GRASP": "sweep/%s/grasp_H%d",
       "CEM": "sweep/%s/cem_H%d", "Ours": "sweep_fk/table/%s/fk_H%d"}
# OURS_PAT points "Ours" at another sweep, e.g. the JALA-EM table:
#   OURS_PAT='sweep_emsmc/table/%s/em_H%d' python writeup/make_main_table.py
PAT["Ours"] = os.environ.get("OURS_PAT", PAT["Ours"])
ENVS = [("Reacher", "reacher"), ("Point maze", "pointmaze"),
        ("Wall", "wall"), ("Push-T", "pusht")]
HS = (5, 10, 15)

def first_pass(sd):
    """Iteration of the first passing evaluation, from run.log.

    Evaluation stops once the task is solved, so the index of the first
    "Success rate:  1.0" line is the iteration at which the planner converged.
    """
    try:
        lines = [l for l in open(sd + "/run.log", errors="ignore")
                 if "Success rate:" in l]
    except OSError:
        return None
    for i, l in enumerate(lines):
        if "1.0" in l.split("Success rate:")[1]:
            return i
    return None


def rate(pat):
    """(success rate %, mean iterations over successful seeds or None)."""
    ok, iters = [], []
    for sd in glob.glob(pat + "/seed_*"):
        rf = sd + "/result.txt"
        if not os.path.exists(rf):
            continue
        r = open(rf).read().split()
        if not r:
            continue
        good = r[0] == "1"
        ok.append(good)
        if good:
            it = first_pass(sd)
            if it is not None:
                iters.append(it)
    if not ok:
        return None
    return (100 * sum(ok) / len(ok),
            sum(iters) / len(iters) if iters else None)

# cells[arm][(env, H)] -> rate
cells = {a: {(e, H): rate(PAT[a] % (e, H)) for _, e in ENVS for H in HS} for a in ARMS}
best = {k: max((cells[a][k][0] for a in ARMS if cells[a][k] is not None), default=None)
        for k in cells[ARMS[0]]}

ncol = len(ENVS) * len(HS)
hdr = " & ".join(r"\multicolumn{%d}{c}{%s}" % (len(HS), n) for n, _ in ENVS)
cmid = " ".join(r"\cmidrule(lr){%d-%d}" % (2 + len(HS) * i, 1 + len(HS) * (i + 1))
                for i in range(len(ENVS)))
sub = " & ".join(str(H) for _ in ENVS for H in HS)

print(r"""% Generated by writeup/make_main_table.py -- do not hand-edit; rerun instead.
% Requires: \usepackage{booktabs}, \usepackage{xcolor}.
\definecolor{bestpurple}{HTML}{5B2C87}
\newcommand{\best}[1]{\textbf{\textcolor{bestpurple}{#1}}}
\begin{table}[h]
  \caption{Planning success rate (\%) with the mean number of optimiser
  iterations to success in parentheses, over $100$ seeds per cell at a matched
  $150$-iteration budget. Iteration counts average over successful seeds only.
  Best success rate per column in bold. An iteration is not a common unit across
  planners -- CEM evaluates $300$ samples per iteration, GD one, ours
  $N$ -- so iteration counts compare within a row, not across rows. Reacher runs $8$ particles; the DINO-WM
  environments run $3$ ($2$ at $H{=}15$), limited by memory. Cube is reported
  separately in Table~\ref{tab:cube}.}
  \label{tab:planners}
  \centering
  \setlength{\tabcolsep}{7pt}
  \renewcommand{\arraystretch}{1.15}
  \resizebox{0.8\textwidth}{!}{%
  \begin{tabular}{l""" + "c" * ncol + r"""}
    \toprule
    & """ + hdr + r""" \\
    """ + cmid + r"""
    Planner & """ + sub + r""" \\
    \midrule""")
for a in ARMS:
    row = []
    for _, e in ENVS:
        for H in HS:
            cell = cells[a][(e, H)]
            if cell is None:
                row.append(r"\textendash")
                continue
            v, it = cell
            num = r"\best{%.0f}" % v if v == best[(e, H)] else "%.0f" % v
            row.append(num if it is None else
                       num + r" \tiny{(%.0f)}" % it)
    if a == "Ours":
        print(r"    \midrule")
        name = r"\textbf{%s}" % LABEL[a]
    else:
        name = LABEL[a]
    print(f"    {name} & " + " & ".join(row) + r" \\")
print(r"""    \bottomrule
  \end{tabular}}
\end{table}""")
