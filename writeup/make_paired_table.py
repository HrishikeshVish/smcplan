"""Per-seed paired comparison of our planner against each baseline.

Success rates say how often each planner solves; they do not say whether the
planners solve the SAME instances. This pairs by seed: W counts seeds we solve
and the baseline does not, L the reverse, T seeds where both agree (solved or
failed). A method that merely trades seeds shows W ~ L; a method that solves a
superset shows L ~ 0.

Generated -- rerun rather than hand-edit.
"""
import glob, os

BASE = [("GD", "sweep/%s/gd_H%d"), ("GRASP", "sweep/%s/grasp_H%d"),
        ("CEM", "sweep/%s/cem_H%d")]
OURS = "sweep_fk/table/%s/fk_H%d"
ENVS = [("Reacher", "reacher"), ("Point maze", "pointmaze"),
        ("Wall", "wall"), ("Push-T", "pusht")]
HS = (5, 10, 15)


def outcomes(pat):
    d = {}
    for sd in glob.glob(pat + "/seed_*"):
        f = sd + "/result.txt"
        if not os.path.exists(f):
            continue
        v = open(f).read().split()
        if v:
            d[int(sd.split("_")[-1])] = (v[0] == "1")
    return d


rows, totals = [], {b: [0, 0, 0] for b, _ in BASE}
for name, env in ENVS:
    for H in HS:
        o = outcomes(OURS % (env, H))
        cells = []
        for b, pat in BASE:
            x = outcomes(pat % (env, H))
            common = sorted(set(o) & set(x))
            w = sum(o[s] and not x[s] for s in common)
            l = sum(x[s] and not o[s] for s in common)
            t = len(common) - w - l
            for i, v in enumerate((w, l, t)):
                totals[b][i] += v
            cells.append((w, l, t))
        rows.append((name if H == HS[0] else "", H, cells))

def fmt(w, l, t):
    body = f"{w} & {l} & {t}"
    return (r"\bad{%d} & %d & %d" % (w, l, t)) if l > w else body

print(r"""% Generated by writeup/make_paired_table.py -- rerun rather than hand-edit.
% Requires: booktabs, xcolor.
\newcommand{\bad}[1]{\textcolor{red!70!black}{#1}}
\begin{table}[h]
  \caption{Per-seed paired outcomes against each baseline, 100 seeds per cell.
  \textbf{W}: we solve and the baseline does not. \textbf{L}: the baseline
  solves and we do not. \textbf{T}: both agree. Success rates alone cannot
  distinguish solving a superset of instances from trading one set for another;
  these columns can. Cells where $L>W$ are marked in red.}
  \label{tab:paired}
  \centering
  \setlength{\tabcolsep}{5pt}
  \begin{tabular}{ll ccc ccc ccc}
    \toprule
    & & \multicolumn{3}{c}{GD} & \multicolumn{3}{c}{GRASP} & \multicolumn{3}{c}{CEM} \\
    \cmidrule(lr){3-5} \cmidrule(lr){6-8} \cmidrule(lr){9-11}
    Environment & $H$ & W & L & T & W & L & T & W & L & T \\
    \midrule""")
prev = None
for name, H, cells in rows:
    if name and prev is not None:
        print(r"    \midrule")
    prev = name or prev
    body = " & ".join(fmt(*c) for c in cells)
    print(f"    {name:11s} & {H:<2d} & {body} \\\\")
print(r"    \midrule")
tot = " & ".join(f"{totals[b][0]} & {totals[b][1]} & {totals[b][2]}" for b, _ in BASE)
print(f"    \\textbf{{Total}} & & {tot} \\\\")
print(r"""    \bottomrule
  \end{tabular}
\end{table}""")
